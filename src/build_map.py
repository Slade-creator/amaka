"""Project the Zambia outline + site coordinates into SVG space for the fleet map.

Reads data/raw/zambia.geojson, writes frontend/src/fleet/zambia.ts.
The projection is equirectangular with a padded 1000x820 viewBox; good enough for
a stylised command map (not a survey-grade map).
"""
from __future__ import annotations

import json
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
GEO = BASE / "data" / "raw" / "zambia.geojson"
OUT = BASE / "frontend" / "src" / "fleet" / "zambia.ts"

W, H = 1000, 820
PAD_X, PAD_Y = 70, 70

# Same site coordinates used by fetch_weather.py / build_forecasts.py.
SITES = {
    "arakan": (-15.435, 28.321),
    "kohima": (-14.406, 28.488),
    "makeni": (-15.47, 28.25),
    "mikango": (-15.329, 28.682),
    "peter_zuze": (-12.9972, 28.6639),
    "tug_argan": (-12.995, 28.665),
}


def main() -> None:
    data = json.loads(GEO.read_text(encoding="utf-8"))
    geom = data["features"][0]["geometry"]
    rings = geom["coordinates"] if geom["type"] == "Polygon" else geom["coordinates"][0]
    ring = max(rings, key=len)

    lons = [p[0] for p in ring]
    lats = [p[1] for p in ring]
    lon_min, lon_max = min(lons), max(lons)
    lat_min, lat_max = min(lats), max(lats)

    def project(lon: float, lat: float) -> tuple[float, float]:
        x = PAD_X + (lon - lon_min) / (lon_max - lon_min) * (W - 2 * PAD_X)
        y = PAD_Y + (lat_max - lat) / (lat_max - lat_min) * (H - 2 * PAD_Y)
        return round(x, 2), round(y, 2)

    parts = []
    for i, (lon, lat) in enumerate(ring):
        x, y = project(lon, lat)
        parts.append(("M" if i == 0 else "L") + f"{x} {y}")
    path = " ".join(parts) + " Z"

    site_lines = []
    for site, (lat, lon) in SITES.items():
        x, y = project(lon, lat)
        site_lines.append(f'  {{ id: "{site}", x: {x}, y: {y} }},')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by src/build_map.py — do not edit by hand.\n"
        f'export const ZAMBIA_VIEWBOX = "0 0 {W} {H}";\n'
        f'export const ZAMBIA_PATH =\n  "{path}";\n\n'
        "export type MapSite = { id: string; x: number; y: number };\n"
        "export const MAP_SITES: MapSite[] = [\n"
        + "\n".join(site_lines)
        + "\n];\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}")
    print(f"lon {lon_min:.3f}..{lon_max:.3f}  lat {lat_min:.3f}..{lat_max:.3f}")
    for site, (lat, lon) in SITES.items():
        print(site, project(lon, lat))


if __name__ == "__main__":
    main()
