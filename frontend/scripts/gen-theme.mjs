// Generates every theme artefact from theme/palette.json:
//   src/theme/theme.css   :root custom properties (--name, --name-rgb)
//   src/theme/tokens.ts   typed TOKENS object for canvas / map / native code
//   android colours.xml   native colours listed under "native"
//   capacitor.config.ts   the splash/background colour (marked block)
// Run with `npm run theme`; `npm run build` and `npm run dev` run it first.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const palette = JSON.parse(readFileSync(path.join(root, "theme", "palette.json"), "utf8"));

const flat = {};
for (const [group, tokens] of Object.entries(palette.groups)) {
  for (const [name, value] of Object.entries(tokens)) {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`Bad token name "${name}" in ${group}`);
    if (!/^#[0-9a-f]{6}$/.test(value)) throw new Error(`Token "${name}" must be #rrggbb lowercase, got "${value}"`);
    if (name in flat) throw new Error(`Duplicate token "${name}"`);
    flat[name] = value;
  }
}
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");
const banner = "GENERATED by scripts/gen-theme.mjs from theme/palette.json. Do not edit by hand.";

mkdirSync(path.join(root, "src", "theme"), { recursive: true });

// ---- CSS -------------------------------------------------------------------
let css = `/* ${banner} */\n:root {\n`;
for (const [group, tokens] of Object.entries(palette.groups)) {
  css += `  /* ${group} */\n`;
  for (const [name, value] of Object.entries(tokens)) {
    css += `  --${name}: ${value};\n  --${name}-rgb: ${rgb(value)};\n`;
  }
}
css += "}\n";
writeFileSync(path.join(root, "src", "theme", "theme.css"), css);

// ---- TS --------------------------------------------------------------------
const entries = Object.entries(flat).map(([k, v]) => `  "${k}": "${v}",`).join("\n");
writeFileSync(
  path.join(root, "src", "theme", "tokens.ts"),
  `// ${banner}\nexport const TOKENS = {\n${entries}\n} as const;\n\nexport type ColorToken = keyof typeof TOKENS;\n`,
);

// ---- Android -----------------------------------------------------------------
const colorsXml = path.join(root, "android", "app", "src", "main", "res", "values", "colors.xml");
if (existsSync(colorsXml)) {
  let xml = readFileSync(colorsXml, "utf8");
  for (const [res, token] of Object.entries(palette.native)) {
    if (res.startsWith("_") || res === "themeColor") continue;
    if (!(token in flat)) throw new Error(`native.${res} names unknown token "${token}"`);
    xml = xml.replace(new RegExp(`(<color name="${res}">)[^<]*(</color>)`), `$1${flat[token]}$2`);
  }
  writeFileSync(colorsXml, xml);
}
// ---- Capacitor config (loaded by the CLI without runtime imports) -----------
const capPath = path.join(root, "capacitor.config.ts");
if (existsSync(capPath)) {
  const bgToken = palette.native.colorPrimary;
  if (!(bgToken in flat)) throw new Error(`native.colorPrimary names unknown token "${bgToken}"`);
  const marker = /(\/\/ theme:begin[^\n]*\n)[\s\S]*?(\/\/ theme:end)/;
  const cap = readFileSync(capPath, "utf8").replace(
    marker,
    (_m, begin, end) => `${begin}const BG = "${flat[bgToken]}";\n${end}`,
  );
  writeFileSync(capPath, cap);
}
console.log(`theme: ${Object.keys(flat).length} tokens -> src/theme/theme.css, src/theme/tokens.ts`);
